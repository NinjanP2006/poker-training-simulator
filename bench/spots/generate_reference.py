"""Generate the 200-spot equity benchmark, using eval7 as an independent reference.

Every number comes from eval7 (https://github.com/julianandrews/pyeval7, on PyPI
as eval7): its range parser expands
the notation, its hand evaluator scores every hand, and its exact
hand-vs-range function scores each complete board. This script only adds the
enumeration over turn/river cards and the range weights, which eval7's exact
function doesn't handle on its own. None of the project's Rust code is used.

Setup (eval7 0.1.10 needs Cython present at build time):
    python -m venv .venv
    .venv/Scripts/python -m pip install cython setuptools wheel
    .venv/Scripts/python -m pip install --no-build-isolation eval7==0.1.10

Usage:
    .venv/Scripts/python generate_reference.py > spots.tsv
"""

import itertools
import random
import sys

import eval7

SEED = 20261015
SPOTS = 200

# Notation accepted by both eval7 and the Rust parser. Covers pairs, suited and
# offsuit runs, both-suitedness classes, specific combos, and weighted groups.
RANGES = [
    "22+, A2s+, KTo+, QJs",
    "QQ+, AKs, AKo",
    "TT+, AQs+, AKo",
    "22+",
    "A2s+, K9s+, Q9s+, J9s+, T8s+, 97s+, 86s+, 75s+, 64s+, 54s",
    "66-JJ",
    "A5o-A9o, KTo+, QJo",
    "KQ, KJ, QJ, JT",
    "AA, KK, 0.5(QQ, JJ, AKs), 25%(AKo)",
    "AsKs, AhKh, QdQc, 7c7d",
    "QQ+, AKs, 0.5(A2s-A5s), 0.3(76s, 65s, 54s)",
    "22+, A2s+, A2o+, K2s+, K8o+, Q8s+, QTo+, J8s+, JTo, T8s+, 97s+, 87s, 76s",
    "88",
    "AKs",
    "0.75(22+), 0.4(A2s+)",
    "77-TT, ATs-AJs, KQs, 0.6(98s, 87s, 76s)",
]

DECK = [str(c) for c in eval7.Deck().cards]


def expand(notation):
    """(cards, weight) pairs from eval7's own parser, cards as strings."""
    return [((str(a), str(b)), w) for (a, b), w in eval7.HandRange(notation).hands]


def reference_equity(hero, board, dead, hands):
    known = set(hero) | set(board) | set(dead)
    live = [(h, w) for h, w in hands if not set(h) & known]
    if not live:
        return None, 0

    by_weight = {}
    for h, w in live:
        by_weight.setdefault(w, []).append(h)
    groups = [(w, hs, [(tuple(map(eval7.Card, h)), 1.0) for h in hs]) for w, hs in by_weight.items()]

    hero_cards = [eval7.Card(c) for c in hero]
    deck = [c for c in DECK if c not in known]
    total = norm = 0.0
    for runout in itertools.combinations(deck, 5 - len(board)):
        full = [eval7.Card(c) for c in list(board) + list(runout)]
        used = set(runout)
        for w, hs, options in groups:
            n = sum(1 for h in hs if not set(h) & used)
            if n:
                eq = eval7.py_hand_vs_range_exact(hero_cards, options, full)
                total += w * eq * n
                norm += w * n
    return total / norm, len(live)


def main():
    rng = random.Random(SEED)
    out = sys.stdout
    out.write("# Equity benchmark: 200 spots, reference values from eval7 0.1.10.\n")
    out.write("# Generated by generate_reference.py; regenerate rather than edit.\n")
    out.write("# Columns: hero, board, dead ('-' = none), villain range, villain combos\n")
    out.write("# before removing blockers (weighted), reference equity.\n")

    made = 0
    while made < SPOTS:
        notation = RANGES[made % len(RANGES)]
        board_size = [3, 4, 5][made % 3]
        cards = rng.sample(DECK, 2 + board_size + 2)
        hero, board = cards[:2], cards[2 : 2 + board_size]
        dead = cards[2 + board_size :] if made % 8 == 7 else []

        hands = expand(notation)
        equity, live = reference_equity(hero, board, dead, hands)
        if equity is None:
            continue  # every combo blocked; draw another spot
        combos = sum(w for _, w in hands)
        out.write(
            "\t".join(
                [
                    " ".join(hero),
                    " ".join(board),
                    " ".join(dead) or "-",
                    notation,
                    f"{combos:g}",
                    f"{equity:.6f}",
                ]
            )
            + "\n"
        )
        out.flush()
        made += 1
        print(f"spot {made}/{SPOTS}: {len(board)}-card board, {live} live combos", file=sys.stderr)


if __name__ == "__main__":
    main()
